"""Export the benchmark's task content as an inspectable dataset.

    python -m dexcraft.dataset --out dataset --n 16

For every ink task family and split it samples N tasks with fixed seeds and writes
  <task>/<split>/<k>_strokes.json  ground truth: stroke polylines [m, sheet frame],
                                   per-point target force [N], instruction, meta
  <task>/<split>/<k>_target.png    high-resolution look at that ground truth (0.25 mm/px,
                                   cropped to the strokes + 1 cm); grey = target force /
                                   FORCE_MAX, line width = the ink the tool would lay
  <task>/<split>/<k>_obsmap.png    THE POLICY'S INPUT, byte for byte: the whole 400 x 300 mm
                                   sheet at 1 mm/px, exactly the array handed over as
                                   obs["task"]["map"]. Inverted for viewing (dark = ink).
  README.md                        frames, units, conventions, how to load
  index.json                       one line per sample + the contract facts
The env is not touched; this is the tasks.py content rendered from its vectors.
"""
import argparse
import json
import os

import numpy as np
from PIL import Image, ImageDraw

from . import tasks as T
from . import scene as S
from .env import DexCraftEnv, INK_MAP_H, INK_MAP_W, INK_MAP_MM_PER_PX

FAMILIES = ["L1_trace_line", "L1_trace_circle", "L1_trace_shape", "L2_write_letters", "L2_write_word",
            "L2_write_digits", "L2_write_chinese", "L2_write_cursive", "L4_sketch_hatching"]
MM_PER_PX = 0.25
MARGIN_M = 0.01


def render_vector(task, mm_per_px=MM_PER_PX, margin=MARGIN_M, ss=4):
    """Anti-aliased crop of the strokes; grey = force / FORCE_MAX, width = ink width."""
    P = np.concatenate([np.asarray(s) for s in task.strokes])
    lo, hi = P.min(0) - margin, P.max(0) + margin
    res = mm_per_px / 1000.0
    W, H = int(np.ceil((hi[0] - lo[0]) / res)), int(np.ceil((hi[1] - lo[1]) / res))
    img = Image.new("L", (W * ss, H * ss), 255)
    d = ImageDraw.Draw(img)
    for k, s_ in enumerate(task.strokes):
        s_ = np.asarray(s_)
        f = task.forces[k] if task.forces is not None else np.full(len(s_), 0.8)
        w = task.widths[k] if task.widths is not None else np.full(len(s_), 1.0)
        for i in range(1, len(s_)):
            a, b = s_[i - 1], s_[i]
            g = int(round(255 * (1.0 - float(np.clip(f[i] / S.FORCE_MAX, 0.0, 1.0)))))
            px = max(1, int(round(w[i] / mm_per_px * ss)))
            xa, ya = (a[0] - lo[0]) / res * ss, (hi[1] - a[1]) / res * ss     # y up on the sheet -> row 0 at the top
            xb, yb = (b[0] - lo[0]) / res * ss, (hi[1] - b[1]) / res * ss
            d.line([(xa, ya), (xb, yb)], fill=g, width=px)
            d.ellipse([xb - px / 2, yb - px / 2, xb + px / 2, yb + px / 2], fill=g)
    return img.resize((W, H), Image.LANCZOS), (lo, hi)


def obs_map_image(env, task):
    """The task map exactly as the policy receives it: the whole sheet at 1 mm/px."""
    win = env._task_window(task)
    tmap = env._rasterize_task_map(task, win)
    return Image.fromarray((255 - tmap).astype(np.uint8)), win


README = """# DexCraft task dataset

Generated by `python -m dexcraft.dataset --out dataset --n {n}`. It is the content of
`dexcraft/tasks.py` rendered from its own vectors - the simulator is not run, so nothing
here depends on a policy or a physics seed.

## Layout

```
<family>/<split>/<k>_strokes.json   ground truth (vectors)
<family>/<split>/<k>_target.png     high-res look at the ground truth
<family>/<split>/<k>_obsmap.png     the policy's input, byte for byte
index.json                          per-sample summary + contract facts
```

`<k>` is a two-digit index; its `seed` is in the JSON (train = 100000+k, test = 200000+k).
`train` and `test` draw from disjoint content pools (`tasks.SPLITS`), so a test glyph is
one the policy has never been trained on.

## The three files

**`_strokes.json`** - the truth, in metres, in the SHEET frame (origin at the sheet
centre, +x right, +y away from the arm base, so it is a right-handed frame seen from
above). `strokes_m` is a list of polylines; `forces_N[i][j]` is the press force asked for
at `strokes_m[i][j]`, taken from real Wacom pen-down curves. `duration_s` is the time
budget. Everything else (`instruction`, `meta`, `extent_mm`, `n_strokes`) is metadata.

**`_target.png`** - the same strokes at {mmpx} mm/px, cropped to the ink plus a 1 cm
margin. Grey level = target force / {fmax} N; line width = the ink that force would lay.
For looking at, not for training.

**`_obsmap.png`** - what `obs["task"]["map"]` actually contains: the **whole sheet**,
{W} x {H} px at {obsmm} mm/px, so one pixel is one millimetre and the image IS the board
at 1:1. Row 0 is the sheet's +y edge. Stored inverted (dark = ink) so it is readable;
the array the policy gets is the other way up - `map = 255 - imread(...)` - with 0 for
background and 1..255 for target force / {fmax} N.

The ink map (`obs["external"]["map"]`) has the same geometry and starts empty.

## Conventions worth knowing before you use it

- Sheet is {sw} x {sh} mm. The maps cover it exactly - same rectangle, same aspect,
  no margin, no square padding.
- Pixel <-> metre: `x_m = (col + 0.5) / {W} * {swm} - {shwm}`,
  `y_m = (1 - (row + 0.5) / {H}) * {shm} - {shhm}` (see `planning.px_to_sheet`).
- Scoring tolerance is 3 mm and the ballpoint line is 1 mm, so at 1 mm/px the map
  resolves both.

## Loading

```python
import json, numpy as np
from PIL import Image
rec = json.load(open("dataset/L2_write_chinese/test/00_strokes.json"))
strokes = [np.array(s) for s in rec["strokes_m"]]          # metres, sheet frame
task_map = 255 - np.array(Image.open("dataset/L2_write_chinese/test/00_obsmap.png"))
assert task_map.shape == ({H}, {W})                        # what the policy sees
```
"""


def write_readme(out, n):
    open(os.path.join(out, "README.md"), "w").write(README.format(
        n=n, mmpx=MM_PER_PX, fmax=S.FORCE_MAX, W=INK_MAP_W, H=INK_MAP_H,
        obsmm=INK_MAP_MM_PER_PX,
        sw=int(2000 * S.PAPER_HALF[0]), sh=int(2000 * S.PAPER_HALF[1]),
        swm=2 * S.PAPER_HALF[0], shwm=S.PAPER_HALF[0],
        shm=2 * S.PAPER_HALF[1], shhm=S.PAPER_HALF[1]))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="dataset")
    ap.add_argument("--n", type=int, default=16)
    ap.add_argument("--families", default=",".join(FAMILIES))
    args = ap.parse_args()
    env = DexCraftEnv("L1_trace_line", obs_mode="state", control_hz=25)     # only for its rasteriser
    index = {"mm_per_px": MM_PER_PX,
             "obs_map": {"res": [INK_MAP_W, INK_MAP_H],
                         "note": "the sheet itself, 1:1 - same rectangle, same aspect",
                         "mm_per_px": INK_MAP_MM_PER_PX,
                         "policy_input": "unchanged; the policy sees exactly this image"},
             "force_max_N": S.FORCE_MAX, "samples": {}}
    for fam in args.families.split(","):
        for split in ("all",):
            d = os.path.join(args.out, fam)
            os.makedirs(d, exist_ok=True)
            for k in range(args.n):
                seed = 100000 * (1 if split == "train" else 2) + k
                task = T.sample(fam, seed)
                img, (lo, hi) = render_vector(task)
                obs, (win_c, win_h) = obs_map_image(env, task)
                img.save(os.path.join(d, f"{k:02d}_target.png"))
                obs.save(os.path.join(d, f"{k:02d}_obsmap.png"))    # native 400x300, never rescaled
                P = np.concatenate([np.asarray(s) for s in task.strokes])
                rec = {"seed": seed, "instruction": task.instruction, "meta": task.meta,
                       "map_window": {"center_m": [float(x) for x in win_c],
                                      "half_m": [float(x) for x in win_h],
                                      "mm_per_px": INK_MAP_MM_PER_PX},
                       "extent_mm": [float(1000 * x) for x in (P.max(0) - P.min(0))],
                       "n_strokes": len(task.strokes), "duration_s": task.duration,
                       "strokes_m": [np.asarray(s).tolist() for s in task.strokes],
                       "forces_N": [np.asarray(f).tolist() for f in task.forces] if task.forces is not None else None}
                json.dump(rec, open(os.path.join(d, f"{k:02d}_strokes.json"), "w"))
                index["samples"].setdefault(fam, {}).setdefault(split, []).append(
                    {k2: rec[k2] for k2 in ("seed", "instruction", "extent_mm", "n_strokes")})
            print(f"{fam:20s} {split:5s} {args.n} samples", flush=True)
    json.dump(index, open(os.path.join(args.out, "index.json"), "w"), indent=1)
    write_readme(args.out, args.n)
    env.close()


if __name__ == "__main__":
    main()
